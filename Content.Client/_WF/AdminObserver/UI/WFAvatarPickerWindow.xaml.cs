using Content.Client._WF.Branding;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.AdminObserver.UI;

/// <summary>
/// Picks the entity prototype an object or mob avatar looks like: the spawn menu's folders and search, with
/// picking an entry in place of placing it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFAvatarPickerWindow : FancyWindow
{
    /// <summary>Raised with the prototype picked, just before the window closes.</summary>
    public event Action<string>? OnPicked;

    public WFAvatarPickerWindow()
    {
        RobustXamlLoader.Load(this);
        WFWindowBranding.Apply(this);

        var avatars = IoCManager.Resolve<IEntityManager>().System<WFAvatarVisualsSystem>();
        Panel.PlacementControlsVisible = false;
        Panel.EntryNote = entry => avatars.CanShow(entry.Id)
            ? null
            : Loc.GetString("wf-observer-preset-prototype-invalid", ("id", entry.Id));
        Panel.OnEntrySelected += entry =>
        {
            if (entry == null || !avatars.CanShow(entry.Id))
                return;

            OnPicked?.Invoke(entry.Id);
            Close();
        };
    }

    protected override void Opened()
    {
        base.Opened();
        Panel.ClearSelection();
        Panel.FocusSearch();
    }
}
