using Content.Client._WF.ShipAdmin.Tabs;
using Content.Shared._WF.ShipAdmin;
using Content.Shared.Administration;
using Content.Shared.Eui;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.ShipAdmin;

/// <summary>The admin ship panel: a list of ships on the left, the selected ship's tabs on the right.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFShipAdminWindow : DefaultWindow
{
    /// <summary>Raised with a message for the server.</summary>
    public event Action<EuiMessageBase>? OnMessage;

    private readonly List<WFShipAdminTab> _tabs = new();
    private List<WFShipAdminRow> _ships = new();
    private bool _truncated;
    private WFShipAdminFilter _filter;
    private NetEntity? _selected;
    private int _resultSeq = -1;

    /// <summary>The overview tab, for tests.</summary>
    public readonly WFShipAdminOverviewTab Overview = new();

    /// <summary>The ownership tab, for tests.</summary>
    public readonly WFShipAdminOwnershipTab Ownership = new();

    /// <summary>The access tab, for tests.</summary>
    public readonly WFShipAdminAccessTab Access = new();

    /// <summary>The repair tab, for tests.</summary>
    public readonly WFShipAdminRepairTab Repair = new();

    /// <summary>The move tab, for tests.</summary>
    public readonly WFShipAdminMoveTab Move = new();

    public WFShipAdminWindow()
    {
        RobustXamlLoader.Load(this);

        AddTab(Overview);
        AddTab(Ownership);
        AddTab(Access);
        AddTab(Repair);
        AddTab(Move);

        SearchBar.OnTextChanged += _ => Populate();
        RefreshButton.OnPressed += _ => OnMessage?.Invoke(new WFShipAdminListMessage(_filter));
        PlayerShipsButton.OnPressed += _ => OnMessage?.Invoke(new WFShipAdminListMessage(WFShipAdminFilter.PlayerShips));
        AllGridsButton.OnPressed += _ => OnMessage?.Invoke(new WFShipAdminListMessage(WFShipAdminFilter.AllGrids));
    }

    private void AddTab(WFShipAdminTab tab)
    {
        _tabs.Add(tab);
        Tabs.AddChild(tab);
        TabContainer.SetTabTitle(tab, tab.Title);
        tab.OnMessage += message => OnMessage?.Invoke(message);
    }

    public void UpdateState(WFShipAdminEuiState state)
    {
        _filter = state.Filter;
        PlayerShipsButton.Pressed = _filter == WFShipAdminFilter.PlayerShips;
        AllGridsButton.Pressed = _filter == WFShipAdminFilter.AllGrids;

        var selected = state.Selected?.Grid;
        if (state.Ships != null || selected != _selected)
        {
            if (state.Ships != null)
            {
                _ships = state.Ships;
                _truncated = state.Truncated;
                foreach (var tab in _tabs)
                    tab.SetShips(_ships);
            }

            _selected = selected;
            Populate();
        }

        NoShipLabel.Visible = state.Selected == null;
        ShipBox.Visible = state.Selected != null;
        if (state.Selected is { } detail)
        {
            ShipNameLabel.Text = detail.Name;
            ShipSummaryLabel.Text = Loc.GetString("wf-ship-admin-summary",
                ("owner", detail.RecordOwner.Length > 0 ? detail.RecordOwner : Loc.GetString("wf-ship-admin-unowned")),
                ("map", detail.Map),
                ("aboard", detail.OccupantCount));

            foreach (var tab in _tabs)
                tab.Update(detail, state.ViewerFlags);
        }

        if (state.ResultSeq != _resultSeq)
        {
            _resultSeq = state.ResultSeq;
            ResultLabel.Text = state.Result;
            ResultLabel.FontColorOverride = state.ResultError ? Color.FromHex("#E05A5A") : null;
        }
    }

    /// <summary>Rebuilds the rows from the last list, the search text and the selection.</summary>
    private void Populate()
    {
        ShipList.RemoveAllChildren();

        var search = SearchBar.Text.Trim().ToLowerInvariant();
        var shown = 0;
        foreach (var ship in _ships)
        {
            if (search.Length > 0
                && !ship.Name.ToLowerInvariant().Contains(search)
                && !ship.Owner.ToLowerInvariant().Contains(search)
                && !ship.Design.ToLowerInvariant().Contains(search))
                continue;

            ShipList.AddChild(MakeRow(ship));
            shown++;
        }

        if (_ships.Count == 0)
            ShipList.AddChild(new Label { Text = Loc.GetString("wf-ship-admin-empty"), Margin = new Thickness(6) });

        CountLabel.Text = Loc.GetString(_truncated ? "wf-ship-admin-count-truncated" : "wf-ship-admin-count", ("shown", shown), ("total", _ships.Count));
    }

    private Control MakeRow(WFShipAdminRow ship)
    {
        var labels = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(4, 1),
        };
        labels.AddChild(new Label { Text = ship.Name, ClipText = true });
        labels.AddChild(new Label
        {
            Text = Loc.GetString("wf-ship-admin-row",
                ("owner", ship.Owner.Length > 0 ? ship.Owner : Loc.GetString("wf-ship-admin-unowned")),
                ("state", ship.OwnerState.ToString().ToLowerInvariant()),
                ("aboard", ship.Occupants)),
            StyleClasses = { "LabelSubText" },
            ClipText = true,
        });

        var button = new ContainerButton
        {
            ToggleMode = true,
            Pressed = ship.Grid == _selected,
            HorizontalExpand = true,
            ToolTip = ship.Map,
        };
        button.AddStyleClass(ContainerButton.StyleClassButton);
        button.AddChild(labels);

        var grid = ship.Grid;
        button.OnPressed += _ => OnMessage?.Invoke(new WFShipAdminSelectMessage(grid));
        return button;
    }
}
